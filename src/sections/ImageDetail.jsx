import { useEffect, useRef, useState } from 'react'
import { createPortal } from 'react-dom'
import { ArrowLeft, ArrowRight, Download, Maximize2, Minimize2 } from 'lucide-react'
import { creativeImages } from '../data/creativeImageMetadata'

function aspectLabel(width, height) {
  if (!width || !height) return 'Loading…'
  const ratio = width / height
  if (Math.abs(ratio - 3 / 2) < 0.015) return '3:2 landscape'
  if (Math.abs(ratio - 16 / 9) < 0.015) return '16:9 landscape'
  if (Math.abs(ratio - 2 / 3) < 0.015) return '2:3 portrait'
  return `${width}:${height}`
}

export default function ImageDetail({ image }) {
  const [dimensions, setDimensions] = useState({ width: 0, height: 0 })
  const [fullScreen, setFullScreen] = useState(false)
  const [viewMode, setViewMode] = useState('fit')
  const closeRef = useRef(null)
  const openRef = useRef(null)
  const index = creativeImages.findIndex(item => item.slug === image.slug)
  const previous = creativeImages[index - 1]
  const next = creativeImages[index + 1]
  const title = image.slug.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join(' ')

  useEffect(() => {
    if (!fullScreen) return
    const previousOverflow = document.body.style.overflow
    const openButton = openRef.current
    document.body.style.overflow = 'hidden'
    closeRef.current?.focus()
    const onKeyDown = event => {
      if (event.key === 'Escape') { event.preventDefault(); setFullScreen(false) }
      if (event.key === 'Tab') {
        const buttons = [...document.querySelectorAll('.lab-image-viewer button')]
        const current = buttons.indexOf(document.activeElement)
        event.preventDefault()
        buttons[(current + (event.shiftKey ? buttons.length - 1 : 1)) % buttons.length]?.focus()
      }
    }
    document.addEventListener('keydown', onKeyDown)
    return () => {
      document.body.style.overflow = previousOverflow
      document.removeEventListener('keydown', onKeyDown)
      openButton?.focus({ preventScroll: true })
    }
  }, [fullScreen])

  return <main className="lab-detail-page">
    <div className="container-custom">
      <nav className="lab-detail-nav" aria-label="Image navigation"><a href="/ai-lab?view=images"><ArrowLeft size={16} /> All images</a><a className="lab-wordmark" href="/">kv<span>✳</span></a></nav>
      <header className="lab-detail-heading"><div><span className="eyebrow">AI LAB / IMAGE {String(index + 1).padStart(2, '0')}</span><h1>{title}</h1><p>{image.alt}</p></div><span className="lab-detail-credit">Generated by ChatGPT</span></header>
      <div className="lab-detail-layout">
        <div className="lab-detail-art"><img src={image.src} alt={image.alt} onLoad={event => setDimensions({ width: event.currentTarget.naturalWidth, height: event.currentTarget.naturalHeight })} /><button ref={openRef} type="button" onClick={() => { setViewMode(image.orientation === 'portrait' ? 'fit' : 'fill'); setFullScreen(true) }}><Maximize2 size={17} /> View full screen</button></div>
        <aside className="lab-detail-info">
          <span className="eyebrow">IMAGE DETAILS</span>
          <dl><div><dt>Generated by</dt><dd>ChatGPT</dd></div><div><dt>Aspect ratio</dt><dd>{aspectLabel(dimensions.width, dimensions.height)}</dd></div><div><dt>Dimensions</dt><dd>{dimensions.width ? `${dimensions.width} × ${dimensions.height} px` : 'Loading…'}</dd></div><div><dt>File format</dt><dd>JPEG</dd></div></dl>
          <div className="lab-detail-prompt"><span className="eyebrow">GENERATION PROMPT</span><p>{image.prompt}</p></div>
          <a className="lab-detail-download" href={image.src} download={image.filename}><Download size={18} /> Download image</a>
        </aside>
      </div>
      <nav className="lab-detail-pagination" aria-label="More AI images">{previous ? <a href={`/ai-lab/images/${previous.slug}`}><ArrowLeft size={16} /><span>Previous image</span></a> : <span />}{next ? <a href={`/ai-lab/images/${next.slug}`}><span>Next image</span><ArrowRight size={16} /></a> : <span />}</nav>
    </div>
    {fullScreen && createPortal(<div className={`lab-image-viewer lab-image-viewer-${viewMode}`} role="dialog" aria-modal="true" aria-label="Full-screen AI image"><img src={image.src} alt={image.alt} /><div className="lab-image-view-controls" role="group" aria-label="Image display mode"><button type="button" aria-pressed={viewMode === 'fit'} onClick={() => setViewMode('fit')}>Fit</button><button type="button" aria-pressed={viewMode === 'fill'} onClick={() => setViewMode('fill')}>Fill</button></div><button ref={closeRef} type="button" className="lab-image-minimize" aria-label="Minimize image" onClick={() => setFullScreen(false)}><Minimize2 size={20} /><span>Minimize</span></button></div>, document.body)}
  </main>
}
